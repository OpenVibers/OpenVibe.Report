-- phase: expand
-- OpenVibe.Report's analytics authority (REP-2, plan 2026-10-28 §4.8 and §5.4).
-- Counts and public channel facts only. Money is never stored here: it is read from OpenVibe.Billing.

-- The inbox of event ids already handled. openvibe-sdk/events createPgInbox() uses
-- (consumer, event_id, processed_at); the extra columns are audit context, never a secret.
CREATE TABLE report_inbox (
    consumer      text NOT NULL,
    event_id      text NOT NULL,
    processed_at  bigint NOT NULL,
    source        text,
    topic         text,
    payload_hash  text,
    received_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (consumer, event_id)
);
CREATE INDEX report_inbox_received ON report_inbox (received_at);

-- The raw event audit trail (public facts only: no viewer ids, no IP addresses, no billing payloads).
CREATE TABLE report_events (
    event_id     text COLLATE "C" PRIMARY KEY,
    source       text COLLATE "C" NOT NULL,
    topic        text COLLATE "C" NOT NULL,
    occurred_at  timestamptz,
    payload      jsonb NOT NULL DEFAULT '{}'::jsonb,
    received_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX report_events_topic_day ON report_events (topic, occurred_at);

-- One row per ended stream; the same fields Network's creator_streams keeps (from live.stream.ended).
CREATE TABLE report_streams (
    stream_id         bigint PRIMARY KEY,
    creator_subject   text COLLATE "C",
    channel           text COLLATE "C" NOT NULL,
    title             text,
    category          text,
    started_at        timestamptz,
    ended_at          timestamptz,
    duration_seconds  bigint NOT NULL DEFAULT 0,
    peak_viewers      bigint,
    avg_viewers       numeric,
    unique_chatters   bigint,
    messages          bigint,
    watch_minutes     bigint,
    payload           jsonb NOT NULL DEFAULT '{}'::jsonb,
    received_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX report_streams_channel_day ON report_streams (lower(channel), started_at DESC);
CREATE INDEX report_streams_creator_day ON report_streams (creator_subject, started_at DESC);

-- The navbar's anonymous beacon, aggregated by day and host.
CREATE TABLE report_frame_days (
    day         date NOT NULL,
    host        text COLLATE "C" NOT NULL,
    hits        bigint NOT NULL DEFAULT 0,
    source      text COLLATE "C" NOT NULL DEFAULT 'frame',
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (day, host)
);

-- A number by day for one scope: scope = network | site | channel | stream.
CREATE TABLE report_metric_days (
    metric      text COLLATE "C" NOT NULL,
    scope       text COLLATE "C" NOT NULL,
    scope_id    text COLLATE "C" NOT NULL,
    day         date NOT NULL,
    value       numeric NOT NULL,
    unit        text COLLATE "C" NOT NULL DEFAULT 'count',
    source      text COLLATE "C" NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (metric, scope, scope_id, day)
);
CREATE INDEX report_metric_days_scope_day ON report_metric_days (scope, scope_id, day);

-- A number for one window (7, 30 or 90 days) when the source published a window total.
CREATE TABLE report_metric_windows (
    metric       text COLLATE "C" NOT NULL,
    scope        text COLLATE "C" NOT NULL,
    scope_id     text COLLATE "C" NOT NULL,
    window_days  integer NOT NULL,
    value        numeric NOT NULL,
    unit         text COLLATE "C" NOT NULL DEFAULT 'count',
    source       text COLLATE "C" NOT NULL,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (metric, scope, scope_id, window_days)
);

-- Lists that are not one number (the busiest route templates, for example).
CREATE TABLE report_metric_json (
    metric       text COLLATE "C" NOT NULL,
    scope        text COLLATE "C" NOT NULL,
    scope_id     text COLLATE "C" NOT NULL,
    window_days  integer NOT NULL,
    value        jsonb NOT NULL,
    source       text COLLATE "C" NOT NULL,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (metric, scope, scope_id, window_days)
);

-- Public labels for a scope: a site's name, host and URL, a channel's display name.
CREATE TABLE report_dimensions (
    kind        text COLLATE "C" NOT NULL,
    id          text COLLATE "C" NOT NULL,
    doc         jsonb NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (kind, id)
);

-- One shadow comparison run and the differences it found. A run with zero differences is a clean run.
CREATE TABLE report_shadow_runs (
    run_id       text COLLATE "C" PRIMARY KEY,
    run_seq      bigint GENERATED BY DEFAULT AS IDENTITY UNIQUE,
    window_days  integer NOT NULL,
    status       text COLLATE "C" NOT NULL,
    checked      integer NOT NULL DEFAULT 0,
    differences  integer NOT NULL DEFAULT 0,
    error        text,
    started_at   timestamptz NOT NULL,
    finished_at  timestamptz
);
CREATE INDEX report_shadow_runs_finished ON report_shadow_runs (finished_at DESC);

CREATE TABLE report_shadow_diffs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id         text COLLATE "C" NOT NULL REFERENCES report_shadow_runs(run_id) ON DELETE CASCADE,
    metric         text COLLATE "C" NOT NULL,
    scope          text COLLATE "C" NOT NULL,
    scope_id       text COLLATE "C" NOT NULL,
    day            date,
    window_days    integer,
    network_value  numeric,
    report_value   numeric,
    delta          numeric,
    network_json   jsonb,
    report_json    jsonb,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX report_shadow_diffs_run ON report_shadow_diffs (run_id, metric, scope, scope_id);
